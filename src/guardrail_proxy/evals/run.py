"""`guardrail-eval`: run evaluation suites and write results/*.json + results/*.md."""

from __future__ import annotations

import argparse
import logging

from guardrail_proxy.config import RESULTS_DIR, get_settings

SUITES = ["injection", "phi", "hallucination", "latency"]


def main() -> None:
    settings = get_settings()
    parser = argparse.ArgumentParser(description="Run guardrail evaluation suites.")
    parser.add_argument("--suite", choices=[*SUITES, "all"], default="all")
    parser.add_argument(
        "--judge-models",
        default=settings.judge_model,
        help="comma-separated judge models for the hallucination suite",
    )
    parser.add_argument("--no-nli", action="store_true", help="skip the NLI baseline judge")
    parser.add_argument(
        "--no-classifier", action="store_true", help="injection suite: heuristic only"
    )
    parser.add_argument(
        "--limit", type=int, default=None, help="hallucination suite: subsample size"
    )
    parser.add_argument(
        "--requests", type=int, default=200, help="latency suite: number of requests"
    )
    args = parser.parse_args()
    logging.basicConfig(level=logging.WARNING)

    suites = SUITES if args.suite == "all" else [args.suite]
    for suite in suites:
        print(f"\n=== {suite} ===", flush=True)
        if suite == "injection":
            from guardrail_proxy.evals import injection_eval

            injection_eval.run(settings, use_classifier=not args.no_classifier)
        elif suite == "phi":
            from guardrail_proxy.evals import phi_eval

            phi_eval.run(settings)
        elif suite == "hallucination":
            from guardrail_proxy.evals import hallucination_eval

            models = [m.strip() for m in args.judge_models.split(",") if m.strip()]
            hallucination_eval.run(settings, models, with_nli=not args.no_nli, limit=args.limit)
        elif suite == "latency":
            from guardrail_proxy.evals import latency_eval

            latency_eval.run(settings, n=args.requests)
    _write_summary()


def _write_summary() -> None:
    parts = [(RESULTS_DIR / f"{s}.md") for s in SUITES]
    body = "\n\n".join(p.read_text(encoding="utf-8").strip() for p in parts if p.exists())
    (RESULTS_DIR / "SUMMARY.md").write_text(
        "# Evaluation results\n\nGenerated by `uv run guardrail-eval`. Raw numbers and error samples "
        "are in the matching `*.json` files.\n\n" + body + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
